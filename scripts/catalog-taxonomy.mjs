export function classifyProduct(product) {
  const name = product.rawName || product.name;
  // Apply the most specific purpose before more general material names.
  const insulationGlue = /тепломонтаж|смесь.*теплоизоляц|штукатурно[ -]клеев.*утепл/iu.test(name);
  const mesh = !/клей|профил|уголок/iu.test(name) && /стеклохолст|[сc]етка/iu.test(name);
  const foamGlue = /пена[ -]клей/iu.test(name);
  const tape = /серпянк|лент|скотч/iu.test(name);
  let match = mesh ? ['Сетки и ленты', tape ? 'Ленты' : 'Сетки и стеклохолст'] : foamGlue ? ['Пены и герметики', 'Пены-клеи'] : insulationGlue ? ['Сухие смеси', 'Клеи для теплоизоляции'] : rules.find(([, , pattern]) => pattern.test(name));
  if (!match) {
    const folder = (product.categoryPath || '').split('/').at(-1);
    const folderGroups = { 'ПЛИТОЧНЫЙ КЛЕЙ': ['Сухие смеси','Плиточные клеи'], 'ШТУКАТУРКА': ['Сухие смеси','Штукатурки'], 'ШПАКЛЕВКА': ['Сухие смеси','Шпаклёвки'], 'КЛАДКА И МОНТАЖ': ['Сухие смеси','Кладка и монтаж'] };
    match = folderGroups[folder];
  }
  if (!match) throw new Error(`Unclassified catalog product: ${product.code} ${name}`);
  return {category: match[0], subgroup: match[1], productKind: match[1]};
}
